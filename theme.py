def tint(h: str, k: float) -> str:
    """مزج اللون مع الأبيض: k=1 اللون الكامل، k=0 أبيض."""
    n = int(h[1:], 16)
    c = [round(255 - (255 - v) * k) for v in (n >> 16 & 255, n >> 8 & 255, n & 255)]
    return "#%02X%02X%02X" % tuple(c)


def shade(h: str, k: float) -> str:
    """تعميق اللون بمزجه مع الأسود: k=1 اللون نفسه، k<1 أغمق."""
    n = int(h[1:], 16)
    c = [round(v * k) for v in (n >> 16 & 255, n >> 8 & 255, n & 255)]
    return "#%02X%02X%02X" % tuple(c)


